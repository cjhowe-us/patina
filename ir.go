package patina

import (
	"math"

	"github.com/alecthomas/participle/v2/lexer"
)

// StageLevel represents the compilation stage, with 0...N-1 being compile time stages
// and Runtime (math.MaxInt) representing the final runtime stage.
type StageLevel int

const (
	// CompileTimeStage0 is the first compile-time stage
	CompileTimeStage0 StageLevel = 0
	// CompileTimeStage1 is the second compile-time stage
	CompileTimeStage1 StageLevel = 1
	// Additional compile-time stages can be defined as needed...

	// Runtime is the final stage that produces the runtime binary
	Runtime StageLevel = math.MaxInt
)

// IR is the intermediate representation for the staged compiler,
// organized by compilation stages
type IR struct {
	// Stages contains the AST for each compilation stage
	// Index corresponds to StageLevel for compile time stages (0...N-1)
	// The last element is for the Runtime stage
	Stages []*StageAST
}

// StageAST represents the AST for a specific compilation stage
type StageAST struct {
	Level StageLevel
	Root  *Root // Reuse the existing AST Root

	// Stage-specific metadata (can be extended as needed)
	CrossStageValues   []*CrossStageValue
	GeneratedFragments []*GeneratedFragment
}

// CrossStageValue represents a value persisted across stages
type CrossStageValue struct {
	Pos        lexer.Position
	Identifier string
	Value      Expression // Reusing AST Expression
	FromStage  StageLevel
	ToStage    StageLevel
}

// GeneratedFragment represents code generated by a higher stage
type GeneratedFragment struct {
	Pos         lexer.Position
	Identifier  string
	Source      *QuoteExpr
	Destination StageLevel
}

// Stage-crossing expressions - minimal set of IR-specific nodes

// QuoteExpr represents a quoted expression (code to be run at a later stage)
type QuoteExpr struct {
	Pos        lexer.Position
	Expression Expression // Reusing AST Expression
	FromStage  StageLevel
	ToStage    StageLevel
}

// Ensure QuoteExpr implements the Expression interface
func (q *QuoteExpr) GetPos() lexer.Position {
	return q.Pos
}

func (QuoteExpr) expression() {} // Implement Expression interface

// SpliceExpr represents a spliced expression (using result from an earlier stage)
type SpliceExpr struct {
	Pos        lexer.Position
	Expression Expression // Reusing AST Expression
	FromStage  StageLevel
	ToStage    StageLevel
}

// Ensure SpliceExpr implements the Expression interface
func (s *SpliceExpr) GetPos() lexer.Position {
	return s.Pos
}

func (SpliceExpr) expression() {} // Implement Expression interface

// StageForExpr represents a stage-annotated expression
type StageForExpr struct {
	Pos        lexer.Position
	Expression Expression // Reusing AST Expression
	Stage      StageLevel
}

// Ensure StageForExpr implements the Expression interface
func (s *StageForExpr) GetPos() lexer.Position {
	return s.Pos
}

func (StageForExpr) expression() {} // Implement Expression interface
